/**
 * 「我的纠纷」需要重拉的跨页信号。
 *
 * 为什么需要它：纠纷列表是分包页，从详情页 `navigateBack` 回来**不会重新挂载**；
 * 而详情页里能做的事（撤回争议、把聊天消息加成证据）都会改变列表上的状态。
 * 但「进详情看一眼就返回」是最常见的动作，每次都重拉纯属白打请求 ——
 * 所以列表加了一道「刚拉过（30 秒内）就别重拉」的时间闸（判据见 `lib/show-reload`）。
 *
 * 时间闸与「刚改过」是两件不同的事，必须区分开：闸只看时间，看不出「你刚在这里撤回了争议」。
 * 因此写操作额外置一个标记，列表显示时先消费标记 —— 有标记就**无视时间闸**直接重拉，
 * 保证「我刚撤回的那条」立刻变样。
 *
 * 纯内存标记，不做持久化：重进小程序后列表本来就会重新挂载取数。
 */
let dirty = false

/** 置位：下一次纠纷列表显示时无视时间闸重拉。 */
export function markDisputesDirty(): void {
  dirty = true
}

/** 消费标记：返回是否需要强制重拉，并把标记清掉（只触发一次）。 */
export function consumeDisputesDirty(): boolean {
  const next = dirty
  dirty = false
  return next
}
